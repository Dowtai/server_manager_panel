// Package installcfg validates first-run settings and generates private deployment configuration.
package installcfg

import (
	"crypto/rand"
	"encoding/base64"
	"encoding/hex"
	"fmt"
	"net/mail"
	"regexp"
	"strconv"
	"strings"

	"golang.org/x/crypto/bcrypt"
)

var usernamePattern = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9_.@-]{2,63}$`)
var domainLabel = regexp.MustCompile(`^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$`)
var emailPattern = regexp.MustCompile(`^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+$`)
var imageID = regexp.MustCompile(`^sha256:[a-f0-9]{64}$`)

type Input struct {
	Username, Password, Domain, Email, RuntimeImage string
	Port                                            int
}

func ValidUsername(s string) bool { return usernamePattern.MatchString(s) }
func ValidDomain(s string) bool {
	if len(s) > 253 || strings.ToLower(s) != s {
		return false
	}
	labels := strings.Split(s, ".")
	if len(labels) < 2 {
		return false
	}
	for _, v := range labels {
		if !domainLabel.MatchString(v) {
			return false
		}
	}
	tld := labels[len(labels)-1]
	return strings.ContainsAny(tld, "abcdefghijklmnopqrstuvwxyz") && len(tld) >= 2
}
func Validate(i Input) error {
	if !ValidUsername(i.Username) {
		return fmt.Errorf("логин: 3–64 символа A–Z, a–z, 0–9, _, ., @, -; первый символ — буква или цифра")
	}
	if len(i.Password) < 12 || len(i.Password) > 72 {
		return fmt.Errorf("пароль: от 12 до 72 байт")
	}
	if !ValidDomain(i.Domain) {
		return fmt.Errorf("укажите домен без https://, пути, порта и wildcard; IDN — в punycode")
	}
	if i.Port < 1 || i.Port > 65535 || i.Port == 80 {
		return fmt.Errorf("порт панели: 1–65535, кроме 80 (он нужен для выпуска и продления сертификата)")
	}
	address, e := mail.ParseAddress(i.Email)
	if e != nil || address.Address != i.Email || !emailPattern.MatchString(i.Email) {
		return fmt.Errorf("укажите обычный email для ACME без имени и дополнительных символов")
	}
	if !imageID.MatchString(i.RuntimeImage) {
		return fmt.Errorf("runtime must be a local Docker sha256 image ID")
	}
	return nil
}
func PublicURL(domain string, port int) string {
	if port == 443 {
		return "https://" + domain
	}
	return "https://" + domain + ":" + strconv.Itoa(port)
}
func randomBytes() ([]byte, error) { b := make([]byte, 32); _, e := rand.Read(b); return b, e }

// Generate never stores the administrator password. The caller writes output with mode 0600.
func Generate(i Input) ([]byte, error) {
	if e := Validate(i); e != nil {
		return nil, e
	}
	hash, e := bcrypt.GenerateFromPassword([]byte(i.Password), 12)
	if e != nil {
		return nil, e
	}
	values := [][2]string{{"INSTALLER_VERSION", "1"}, {"ADMIN_USERNAME", i.Username}, {"ADMIN_PASSWORD_HASH", string(hash)}, {"PANEL_DOMAIN", i.Domain}, {"PANEL_PORT", strconv.Itoa(i.Port)}, {"ACME_EMAIL", i.Email}, {"PUBLIC_URL", PublicURL(i.Domain, i.Port)}, {"INSECURE_COOKIE", "false"}, {"API_HOST_PORT", "0"}, {"AWG_RUNTIME_IMAGE", i.RuntimeImage}, {"AWG_RUNTIME_ARCHIVE", "/runtime/runtime.tar"}, {"TELEGRAM_BOT_TOKEN", ""}}
	for _, name := range []string{"POSTGRES_PASSWORD", "ENCRYPTION_KEY", "SESSION_KEY", "SERVICE_TOKEN"} {
		b, e := randomBytes()
		if e != nil {
			return nil, e
		}
		v := base64.StdEncoding.EncodeToString(b)
		if name == "POSTGRES_PASSWORD" {
			v = hex.EncodeToString(b)
		}
		values = append(values, [2]string{name, v})
	}
	var out strings.Builder
	out.WriteString("# Generated by install.sh. Keep this file and the encryption key in your backup.\n")
	for _, p := range values {
		fmt.Fprintf(&out, "%s='%s'\n", p[0], p[1])
	}
	return []byte(out.String()), nil
}
